#!/usr/bin/env python3
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, ListFlowable, ListItem
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
import os


def register_cyrillic_font() -> str:
    """Register a Unicode font that supports Cyrillic. Returns the font name."""
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
        os.path.expanduser("~/.local/share/fonts/DejaVuSans.ttf"),
        os.path.expanduser("~/.fonts/DejaVuSans.ttf"),
    ]
    for path in candidates:
        if os.path.exists(path):
            pdfmetrics.registerFont(TTFont("UIFont", path))
            return "UIFont"
    # Fallback (might not render Cyrillic correctly, but prevents crash)
    return "Helvetica"


def build_styles(font_name: str):
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle("TitleCyr", parent=styles["Title"], fontName=font_name, leading=24))
    styles.add(ParagraphStyle("HeadingCyr", parent=styles["Heading2"], fontName=font_name, spaceBefore=10, spaceAfter=4))
    styles.add(ParagraphStyle("BodyCyr", parent=styles["BodyText"], fontName=font_name, leading=14))
    styles.add(ParagraphStyle("SmallCyr", parent=styles["BodyText"], fontName=font_name, fontSize=9, leading=11, textColor="#555555"))
    return styles


def bullet(items, styles, left=10*mm):
    flow_items = []
    for it in items:
        if isinstance(it, (list, tuple)):
            # Nested list
            flow_items.append(ListFlowable(
                [ListItem(Paragraph(txt, styles["BodyCyr"])) for txt in it],
                bulletType="bullet",
                leftIndent=left + 6*mm,
            ))
        else:
            flow_items.append(ListItem(Paragraph(it, styles["BodyCyr"])) )
    return ListFlowable(flow_items, bulletType="bullet", leftIndent=left)


def header_footer(canvas, doc, font_name: str):
    canvas.saveState()
    canvas.setFont(font_name, 9)
    # Header
    canvas.drawString(15*mm, A4[1] - 12*mm, "Шпаргалка: Латина, розділ 1")
    # Footer with page number
    canvas.drawRightString(A4[0] - 15*mm, 10*mm, f"Стор. {doc.page}")
    canvas.restoreState()


def build_document(path: str):
    font_name = register_cyrillic_font()
    styles = build_styles(font_name)

    doc = SimpleDocTemplate(
        path,
        pagesize=A4,
        leftMargin=15*mm,
        rightMargin=15*mm,
        topMargin=18*mm,
        bottomMargin=15*mm,
        title="Шпаргалка латина розділ 1",
        author="Generated by ReportLab",
    )

    story = []

    story.append(Paragraph("Шпаргалка: латина, розділ 1", styles["TitleCyr"]))
    story.append(Paragraph("Стисла пам'ятка для підготовки", styles["SmallCyr"]))
    story.append(Spacer(1, 6))

    # Вокабуляр і етимологія
    story.append(Paragraph("Вокабуляр і етимологія", styles["HeadingCyr"]))
    story.append(bullet([
        "Вивчи словник розділу; розпізнавай значення за латинським коренем.",
        "Типові префікси: <b>ab-/ā-</b> (від), <b>ad-</b> (до), <b>in-</b> (у/на; інколи ‘не-’), <b>ex-</b> (з/із), <b>de-</b> (згори/про-), <b>per-</b> (крізь/дуже), <b>sub-</b> (під), <b>trans-</b> (через), <b>inter-</b> (між), <b>contra-</b> (проти).",
        "Часті суфікси: <b>-tio/-sio</b> (дія), <b>-tor/-trix</b> (діяч), <b>-mentum</b> (засіб/результат), <b>-arium</b> (місце).",
    ], styles))

    # 1-а відміна
    story.append(Paragraph("1-а відміна (на -a)", styles["HeadingCyr"]))
    story.append(bullet([
        "Основу знай з GEN SG: puella, puellae → основа <b>puell-</b>.",
        "Закінчення однини: <b>N -a</b>, <b>G -ae</b>, <b>D -ae</b>, <b>Acc -am</b>, <b>Abl -ā</b>, <b>V -a</b>.",
        "Закінчення множини: <b>N -ae</b>, <b>G -ārum</b>, <b>D -īs</b>, <b>Acc -ās</b>, <b>Abl -īs</b>, <b>V -ae</b>.",
        [
            "Функції відмінків:",
            "Nominativus — підмет, іменна частина присудка.",
            "Genitivus — приналежність (кого? чого?).",
            "Dativus — адресат (кому?).",
            "Accusativus — прямий додаток; напрямок (куди?).",
            "Ablativus — обставини (чим/ким/де/коли/від чого).",
            "Vocativus — звертання.",
        ],
    ], styles))

    # Граматика
    story.append(Paragraph("Граматика", styles["HeadingCyr"]))
    story.append(bullet([
        [
            "Відповідність синтаксису:",
            "Sujet → Nominativus; COD → Accusativus;",
            "COI → Dativus; Complément du nom → Genitivus;",
            "Обставини (місце/час/засіб/причина) → Ablativus.",
        ],
        [
            "Прийменники:",
            "a/ab + Abl = від; агенс у пасиві (ab amīcō).",
            "apud + Acc = у/біля когось; ‘у автора/творі’.",
            "in + Abl = де? (статично); in + Acc = куди? (рух).",
        ],
        "Прикметник узгоджується з іменником у роді, числі, відмінку.",
        "Порядок слів зазвичай S–O–V; вирішальні — закінчення.",
        "Лічба до 10: <b>ūnus</b>, <b>duo</b>, <b>trēs</b>, <b>quattuor</b>, <b>quīnque</b>, <b>sex</b>, <b>septem</b>, <b>octō</b>, <b>novem</b>, <b>decem</b> (I–X).",
    ], styles))

    # Дієвідміна
    story.append(Paragraph("Дієвідміна (indicativus praesens)", styles["HeadingCyr"]))
    story.append(bullet([
        [
            "Особові закінчення:",
            "1-а (-āre): -ō, -ās, -at, -āmus, -ātis, -ant (amō).",
            "2-а (-ēre): -eō, -ēs, -et, -ēmus, -ētis, -ent (habeō).",
            "3-я (-ere): -ō, -is, -it, -imus, -itis, -unt (mittō).",
            "3-я зміш. (-io, -ere): -iō, -is, -it, -imus, -itis, -iunt (capiō).",
            "4-а (-īre): -iō, -īs, -it, -īmus, -ītis, -iunt (audiō).",
        ],
        [
            "Дієслово ‘бути’:",
            "sum, es, est, sumus, estis, sunt; інф. esse; інші форми: fuī, futūrus.",
            "Складені: adsum/absum/desum; possum, potes, potest, possumus, potestis, possunt.",
        ],
        [
            "Шаблон 4 форм (приклади):",
            "amō, amāre, amāvī, amātum; habeō, habēre, habuī, habitum;",
            "mittō, mittere, mīsī, missum; audiō, audīre, audīvī, audītum;",
            "capiō, capere, cēpī, captum.",
        ],
    ], styles))

    # Переклад алгоритм
    story.append(Paragraph("Переклад короткого речення (алгоритм)", styles["HeadingCyr"]))
    story.append(bullet([
        "Знайди присудок (особа/число/час).",
        "Визнач підмет (Nominativus).",
        "Визнач додатки (Acc/DAT/GEN) і обставини (Abl з/без прийм.).",
        "Перевір узгодження прикметників; відтворюй зміст, а не порядок слів.",
    ], styles))

    # Цивілізація
    story.append(Paragraph("Цивілізація", styles["HeadingCyr"]))
    story.append(bullet([
        [
            "Три періоди історії Риму:",
            "Монархія: 753–509 до н.е.",
            "Республіка: 509–27 до н.е.",
            "Імперія: 27 до н.е. – 476 н.е. (Захід).",
        ],
        "Дата заснування Риму: 753 до н.е. (Ромул).",
        [
            "Боги/богині (лат. → грец. → атрибут):",
            "Iuppiter → Zeus — блискавка, орел; Iūnō → Hera — шлюб; Minerva → Athena — мудрість;",
            "Mars → Ares — війна; Venus → Aphrodite — кохання; Mercurius → Hermes — торг;",
            "Neptūnus → Poseidon — море; Diana → Artemis — полювання; Apollō → Apollōn — мистецтва;",
            "Vesta → Hestia — домашнє вогнище.",
        ],
        [
            "Римська Гельветія:",
            "Столиця: Aventicum (сьогодні Avenches).",
            "Територія: Швейцарське Серединне плато між Юрою та Альпами.",
            "Via Romana: прямолінійний шлях; міліарії (M·P), прямота трас, топоніми на ‘via’.",
        ],
    ], styles))

    # Часті помилки
    story.append(Paragraph("Часті помилки", styles["HeadingCyr"]))
    story.append(bullet([
        "Не плутай in + Acc (рух) з in + Abl (статично).",
        "У пасиві агенс лише з a/ab + Abl.",
        "Основу іменника визначай від GEN SG, а не від NOM SG.",
    ], styles))

    # Build document with header/footer
    doc.build(
        story,
        onFirstPage=lambda c, d: header_footer(c, d, font_name),
        onLaterPages=lambda c, d: header_footer(c, d, font_name),
    )


if __name__ == "__main__":
    output = os.path.abspath("cheatsheet_latin_ch1.pdf")
    build_document(output)
    print(output)
